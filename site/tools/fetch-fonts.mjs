// Self-hosts the site's fonts at build time: no request to Google from visitors' browsers.
// Usage: node site/tools/fetch-fonts.mjs   (writes site/fonts/fonts.css and site/fonts/*.woff2)
//
// Everything downloaded is treated as untrusted: only fonts.gstatic.com URLs are followed,
// files must be real WOFF2 under a size cap, names are generated locally, and the stylesheet
// is rebuilt from parsed values instead of being copied as received.
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "fonts");
const families = ["Big+Shoulders+Display:wght@200..800", "Geist:wght@300..600", "Geist+Mono:wght@400;500"];
const cssUrl = `https://fonts.googleapis.com/css2?${families.map((f) => `family=${f}`).join("&")}&display=swap`;
// A current browser user agent makes Google serve woff2 with unicode-range subsets.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";
const MAX_FONT_BYTES = 512 * 1024;
const KEEP_SUBSETS = new Set(["latin", "latin-ext"]);
const ALLOWED_FAMILIES = new Set(["Big Shoulders Display", "Geist", "Geist Mono"]);

const res = await fetch(cssUrl, { headers: { "user-agent": UA } });
if (!res.ok) throw new Error(`fonts css: HTTP ${res.status}`);
const css = await res.text();

/** Parse the @font-face blocks we expect, and nothing else. */
const faces = [];
for (const m of css.matchAll(/\/\* ([a-z-]+) \*\/\s*@font-face\s*{([^}]*)}/g)) {
  const [, subset, body] = m;
  if (!KEEP_SUBSETS.has(subset)) continue;
  const get = (prop) => new RegExp(`${prop}:\\s*([^;]+);`).exec(body)?.[1].trim();
  const family = get("font-family")?.replace(/^['"]|['"]$/g, "");
  const weight = get("font-weight");
  const style = get("font-style") ?? "normal";
  const range = get("unicode-range");
  const src = /url\((https:\/\/[^)]+)\)\s*format\('woff2'\)/.exec(body)?.[1];
  if (!family || !ALLOWED_FAMILIES.has(family)) continue;
  if (!weight || !/^\d{3}( \d{3})?$/.test(weight)) throw new Error(`unexpected font-weight: ${weight}`);
  if (!/^(normal|italic)$/.test(style)) throw new Error(`unexpected font-style: ${style}`);
  if (!range || !/^[U+0-9A-Fa-f?, -]+$/.test(range)) throw new Error(`unexpected unicode-range: ${range}`);
  if (!src || new URL(src).hostname !== "fonts.gstatic.com") throw new Error(`unexpected font source: ${src}`);
  faces.push({ family, weight, style, range, src });
}
if (!faces.length) throw new Error("no font faces parsed: the Google Fonts response format changed");

await mkdir(out, { recursive: true });
const files = new Map();
let rules = "";
for (const face of faces) {
  let name = files.get(face.src);
  if (!name) {
    const r = await fetch(face.src);
    if (!r.ok) throw new Error(`${face.src}: HTTP ${r.status}`);
    const buf = Buffer.from(await r.arrayBuffer());
    if (buf.length > MAX_FONT_BYTES) throw new Error(`${face.src}: ${buf.length} bytes exceeds the cap`);
    if (buf.subarray(0, 4).toString("latin1") !== "wOF2") throw new Error(`${face.src}: not a WOFF2 file`);
    name = `font-${String(files.size).padStart(2, "0")}.woff2`; // generated locally, never taken from the network
    await writeFile(join(out, name), buf);
    files.set(face.src, name);
  }
  rules +=
    `@font-face { font-family: "${face.family}"; font-style: ${face.style}; font-weight: ${face.weight}; ` +
    `font-display: swap; src: url(./${name}) format("woff2"); unicode-range: ${face.range}; }\n`;
}
await writeFile(join(out, "fonts.css"), `/* Generated by site/tools/fetch-fonts.mjs. Fonts: SIL Open Font License. */\n${rules}`);
console.log(`fonts: ${faces.length} faces, ${files.size} files written to ${out}`);
