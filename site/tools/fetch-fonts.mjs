// Self-hosts the site's fonts at build time: no request to Google from visitors' browsers.
// Usage: node site/tools/fetch-fonts.mjs   (writes site/fonts/fonts.css and site/fonts/*.woff2)
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "fonts");
const families = [
  "Big+Shoulders+Display:wght@200..800",
  "Geist:wght@300..600",
  "Geist+Mono:wght@400;500",
];
const url = `https://fonts.googleapis.com/css2?${families.map((f) => `family=${f}`).join("&")}&display=swap`;
// A current browser user agent makes Google serve woff2 with unicode-range subsets.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";

const res = await fetch(url, { headers: { "user-agent": UA } });
if (!res.ok) throw new Error(`fonts css: HTTP ${res.status}`);
let css = await res.text();
await mkdir(out, { recursive: true });

// Keep only latin and latin-ext subsets: the site is in English.
css = css.replace(/\/\* ([a-z-]+) \*\/\s*@font-face\s*{[^}]*}/g, (block, subset) => (["latin", "latin-ext"].includes(subset) ? block : ""));

const urls = [...new Set([...css.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map((m) => m[1]))];
let n = 0;
for (const u of urls) {
  const name = `f${String(n++).padStart(2, "0")}-${u.split("/").pop()}`;
  const file = await fetch(u);
  if (!file.ok) throw new Error(`${u}: HTTP ${file.status}`);
  await writeFile(join(out, name), Buffer.from(await file.arrayBuffer()));
  css = css.split(u).join(`./${name}`);
}
await writeFile(join(out, "fonts.css"), `/* Generated by site/tools/fetch-fonts.mjs. SIL Open Font License. */\n${css}`);
console.log(`fonts: ${urls.length} files written to ${out}`);
